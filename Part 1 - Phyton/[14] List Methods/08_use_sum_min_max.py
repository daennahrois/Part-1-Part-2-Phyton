# 8: Use sum(), min(), and max() 
grades = [85, 90, 78, 92, 88]
print("Total:", sum(grades))
print("Lowest:", min(grades))
print("Highest:", max(grades))
print("Count:", len(grades))
average = sum(grades) / len(grades)
print("Average:", average)
print("Range:", max(grades) - min(grades))
words = ["pear", "apple", "mango"]
print("First alphabetically:", min(words))
print("Last alphabetically:", max(words))