# 5: Sort a List
scores = [88, 72, 95, 60]
print("Original:", scores)
scores.sort()
print("Ascending:", scores)
scores.sort(reverse=True)
print("Descending:", scores)
names = ["Carla", "Ana", "Ben"]
names.sort()
print("Names:", names)
grades = [90, 75, 85]
new_grades = sorted(grades)
print("New list:", new_grades)
print("Original:", grades)