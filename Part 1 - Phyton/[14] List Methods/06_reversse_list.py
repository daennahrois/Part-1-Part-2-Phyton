# 6: Reverse a List
numbers = [1, 2, 3, 4, 5]
print("Original:", numbers)
numbers.reverse()
print("Reversed:", numbers)
letters = ["x", "y", "z"]
backwards = letters[::-1]
print("Copy reversed:", backwards)
print("Original:", letters)
scores = [70, 95, 82]
scores.sort()
scores.reverse()
print("Highest first:", scores)